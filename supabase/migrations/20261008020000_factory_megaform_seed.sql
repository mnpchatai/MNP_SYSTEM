    select i.id, 'A', (k.e ->> 8)::numeric, 'approved', date '2026-07-14', v_mark, 3, v_persona.id, v_admin.id,
           v_persona.id, now(), v_admin.id, now(), 'อนุมัติพร้อมชุดทดสอบ'
    from (select distinct e ->> 0 as parent from jsonb_array_elements(v_lines) e) p
    join public.factory_items i on i.is_test and i.code = p.parent
    join lateral (select e from jsonb_array_elements(v_items) e where e ->> 0 = p.parent) k on true
    returning id
  )
  select array_agg(id), count(*) into v_bom_ids, v_boms_n from ins;

  insert into public.factory_bom_lines (bom_id, line_no, component_id, quantity, scrap_percent)
  select b.id, (row_number() over (partition by l.parent order by l.ord))::integer, c.id, l.qty, 0
  from (select e ->> 0 as parent, e ->> 1 as comp, (e ->> 2)::numeric as qty, t.ord
        from jsonb_array_elements(v_lines) with ordinality as t(e, ord)) l
  join public.factory_items p on p.is_test and p.code = l.parent
  join public.factory_boms b on b.item_id = p.id and b.revision = 'A'
  join public.factory_items c on c.is_test and c.code = l.comp;
  get diagnostics v_lines_n = row_count;

  insert into public.factory_bom_history (bom_id, action, version, status_after, note, snapshot, changed_by)
  select b.id, h.action, h.version, h.status_after, h.note, private.factory_bom_snapshot(b.id), h.changed_by
  from public.factory_boms b
  cross join (values
    ('create', 1, 'draft', v_mark, v_persona.id),
    ('submit', 2, 'pending_approval', '', v_persona.id),
    ('approve', 3, 'approved', 'อนุมัติพร้อมชุดทดสอบ', v_admin.id)
  ) as h(action, version, status_after, note, changed_by)
  where b.id = any (v_bom_ids);

  -- 3. Routing ตามชนิดชิ้นงาน (ฉบับร่าง เหมือนชุดทดลอง 5 สินค้า)
  insert into public.factory_routings (item_id, revision, status)
  select b.item_id, 'A', 'draft' from public.factory_boms b where b.id = any (v_bom_ids);

  insert into public.factory_routing_steps (routing_id, sequence, name, work_center_id, setup_minutes, run_minutes, instruction)
  select r.id, (t.ord * 10)::integer, t.s ->> 0, w.id, (t.s ->> 2)::numeric, (t.s ->> 3)::numeric,
         'เวลาตัวอย่างต่อชุดผลิต ต้องยืนยันกับหน้างาน'
  from public.factory_routings r
  join public.factory_boms b on b.item_id = r.item_id and b.id = any (v_bom_ids)
  join public.factory_items i on i.id = r.item_id
  join lateral (select e ->> 1 as kind from jsonb_array_elements(v_items) e where e ->> 0 = i.code) k on true
  join lateral jsonb_array_elements(v_steps -> k.kind) with ordinality as t(s, ord) on true
  join public.factory_work_centers w on w.is_test and w.code = t.s ->> 1
  where r.is_test and r.revision = 'A';
  get diagnostics v_steps_n = row_count;

  -- 4. ใบสั่งผลิต: เดิน workflow เดิม สร้าง→ส่ง→รับ→วางแผน→ออกใบสั่งงาน
  for v_row in
    select (e ->> 0) as fg, (e ->> 1)::numeric as qty, e ->> 2 as grp, t.ord
    from jsonb_array_elements(v_orders) with ordinality as t(e, ord)
    order by t.ord
  loop
    select i.id into v_item_id from public.factory_items i where i.is_test and i.code = v_row.fg;
    select b.id into v_bom_id from public.factory_boms b where b.item_id = v_item_id and b.revision = 'A';
    select r.id into v_routing_id from public.factory_routings r where r.item_id = v_item_id and r.revision = 'A';

    insert into public.factory_production_orders (code, item_id, planned_qty, status, due_date, customer, note, created_by, updated_by)
    values (private.next_factory_doc_number('MO'), v_item_id, v_row.qty, 'draft', v_due, v_customer,
            v_mark || ' • ประเทศ Belgium • สั่งผลิต 2026-07-14 • กลุ่มในใบคำนวณ ' || btrim(v_row.grp), v_persona.id, v_persona.id)
    returning * into v_order;
    perform private.factory_order_log(v_order.id, 'create', '', v_persona);

    update public.factory_production_orders
    set status = 'submitted', version = 2, submitted_by = v_persona.id, submitted_at = now(), updated_by = v_persona.id, updated_at = now()
    where id = v_order.id;
    perform private.factory_order_log(v_order.id, 'submit', '', v_persona);

    update public.factory_production_orders
    set status = 'planning', version = 3, received_by = v_persona.id, received_at = now(), updated_by = v_persona.id, updated_at = now()
    where id = v_order.id;
    perform private.factory_order_log(v_order.id, 'receive', '', v_persona);

    update public.factory_production_orders
    set status = 'planned', version = 4, bom_id = v_bom_id, routing_id = v_routing_id,
        survey_note = 'สำรวจคงคลังตามใบคำนวณวัตถุดิบ 260702-26031 (ผลิต/สั่งซื้อเฉพาะส่วนที่เกินคงคลัง)',
        planned_by = v_persona.id, planned_at = now(), updated_by = v_persona.id, updated_at = now()
    where id = v_order.id;
    perform private.factory_order_log(v_order.id, 'plan', 'สำรวจคงคลังตามใบคำนวณวัตถุดิบ 260702-26031', v_persona);

    update public.factory_production_orders
    set status = 'released', version = 5, work_order_no = private.next_factory_doc_number('WO'),
        released_by = v_persona.id, released_at = now(), updated_by = v_persona.id, updated_at = now()
    where id = v_order.id;
    perform private.factory_order_log(v_order.id, 'release', '', v_persona);

    v_order_ids := v_order_ids || v_order.id;
  end loop;

  -- 5. ใบงานของทุกแผนก พร้อมวันที่ตามแผน (เหมือน app_factory_create_job แล้ว app_factory_schedule_job)
  for v_row in
    select (e ->> 0)::integer as oi, e ->> 1 as item, (e ->> 2)::numeric as qty, (e ->> 3)::date as plan_start, (e ->> 4)::date as plan_end, t.ord
    from jsonb_array_elements(v_jobs) with ordinality as t(e, ord)
    order by t.ord
  loop
    select i.id into v_item_id from public.factory_items i where i.is_test and i.code = v_row.item;
    select k.e ->> 1 into v_kind from jsonb_array_elements(v_items) k(e) where k.e ->> 0 = v_row.item;
    select b.id into v_bom_id from public.factory_boms b where b.item_id = v_item_id and b.status = 'approved';
    select r.id into v_routing_id from public.factory_routings r where r.item_id = v_item_id and r.revision = 'A';
    select w.id into v_warehouse_id from public.factory_warehouses w
    where w.is_test and w.code = case v_kind when 'FG' then 'FG' when 'RB' then 'SR' else 'WIP' end;

    insert into public.factory_jobs (code, production_order_id, item_id, bom_id, routing_id, warehouse_id, qty, note, created_by, updated_by)
    values (private.next_factory_doc_number('JB'), v_order_ids[v_row.oi], v_item_id, v_bom_id, v_routing_id, v_warehouse_id, v_row.qty,
            v_mark, v_persona.id, v_persona.id)
    returning * into v_job;
    insert into public.factory_job_steps (job_id, sequence, name, work_center_code, instruction, setup_minutes, run_minutes)
    select v_job.id, s.sequence, s.name, w.code, s.instruction, s.setup_minutes, s.run_minutes
    from public.factory_routing_steps s join public.factory_work_centers w on w.id = s.work_center_id
    where s.routing_id = v_routing_id;
    perform private.factory_job_log(v_job.id, 'create', null, '', v_persona);

    update public.factory_jobs
    set planned_start = v_row.plan_start, planned_end = v_row.plan_end, schedule_version = 2,
        scheduled_by = v_persona.id, scheduled_at = now(), updated_by = v_persona.id, updated_at = now()
    where id = v_job.id;
    perform private.factory_job_log(v_job.id, 'schedule', null, '', v_persona);
    v_jobs_n := v_jobs_n + 1;
  end loop;

  -- 6. ยอดยกมา (ไม่ใช้ล็อต: ทุก Item ปิดการติดตามล็อต)
  insert into public.factory_inventory_movements (item_id, warehouse_id, lot_id, quantity, kind, reference, created_by)
  select i.id, w.id, null, (s ->> 1)::numeric, 'opening', 'ยอดยกมาตามใบคำนวณวัตถุดิบ 260702-26031 (ข้อมูลทดสอบ)', v_persona.id
  from jsonb_array_elements(v_stock) as s
  join public.factory_items i on i.is_test and i.code = s ->> 0
  join public.factory_warehouses w on w.is_test and w.code = s ->> 2;
  get diagnostics v_moves_n = row_count;

  insert into public.audit_logs (actor_id, action, entity_type, entity_id, metadata)
  values (v_admin.id, 'SANDBOX_SEED_FACTORY_MEGAFORM', 'sandbox_session', v_admin.id::text,
          jsonb_build_object('items', v_items_n, 'boms', v_boms_n, 'bom_lines', v_lines_n, 'routing_steps', v_steps_n,
                             'orders', jsonb_array_length(v_orders), 'jobs', v_jobs_n, 'opening_balances', v_moves_n,
                             'persona_employee_no', v_persona.employee_no));
  return jsonb_build_object('seeded', true, 'items', v_items_n, 'boms', v_boms_n, 'steps', v_steps_n,
                            'orders', jsonb_array_length(v_orders), 'jobs', v_jobs_n);
end;
$$;

