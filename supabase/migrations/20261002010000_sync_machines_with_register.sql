-- RB, GR, PT, MT ตรงกับ Excel ครบทุกแถว ที่ต่างมี 2 เรื่อง:
--
-- 1. ST 4 เครื่อง: migration 20260917101500 ใส่รหัสกับชื่อสลับช่องกัน (code = "รอกไฟฟ้า", name = "F-LF1-1")
--    ผู้แจ้งจึงค้นด้วยรหัส F-LF1-1 ไม่เจอ และใบแจ้งซ่อมจะเก็บรหัสเป็นชื่อเครื่อง
--    ตรวจแล้วยังไม่มีใบแจ้งซ่อมอ้างเครื่องกลุ่มนี้ จึงสลับกลับได้โดยไม่ต้องแก้ใบเก่า
